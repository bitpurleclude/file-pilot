import { afterEach, describe, expect, it, vi } from "vitest";

import { RuleFirstLlmClassifier } from "../../infra/llm/rule-first-llm.js";
import type { AppSettings } from "../../shared/types/settings.js";

const originalFetch = globalThis.fetch;

afterEach(() => {
  globalThis.fetch = originalFetch;
  vi.restoreAllMocks();
});

describe("rule-first-llm classifier", () => {
  it("parses JSON response generated by template-based prompt", async () => {
    globalThis.fetch = vi.fn(async () => {
      return {
        ok: true,
        json: async () => ({
          choices: [
            {
              message: {
                content: JSON.stringify({
                  purpose: "Documents",
                  project: "文档项目",
                  confidence: 0.91,
                  reasons: ["llm-判断"]
                })
              }
            }
          ]
        })
      } as Response;
    }) as typeof fetch;

    const settings: AppSettings = {
      whitelistDirectories: [],
      llm: {
        baseUrl: "https://example.com/v1",
        apiKey: "test-key",
        primaryModel: "gpt-4.1",
        secondaryModel: "gpt-4.1-mini"
      }
    };

    const classifier = new RuleFirstLlmClassifier(settings);
    const result = await classifier.classify({
      item: {
        id: "1",
        path: "C:/a/note.md",
        name: "note.md",
        ext: "md",
        size: 10,
        createdAt: "2026-02-12T00:00:00.000Z",
        modifiedAt: "2026-02-12T00:00:00.000Z",
        mime: "text/markdown"
      },
      summary: {
        textSnippet: "测试",
        keywords: ["测试"],
        language: "zh-CN"
      }
    });

    expect(result).not.toBeNull();
    expect(result?.purpose).toBe("Documents");
    expect(result?.reasons.some((item) => item.startsWith("prompt_version:"))).toBe(true);
  });

  it("falls back to local rule when llm returns invalid payload", async () => {
    globalThis.fetch = vi.fn(async () => {
      return {
        ok: true,
        json: async () => ({
          choices: [{ message: { content: "not-json" } }]
        })
      } as Response;
    }) as typeof fetch;

    const settings: AppSettings = {
      whitelistDirectories: [],
      llm: {
        baseUrl: "https://example.com/v1",
        primaryModel: "gpt-4.1",
        secondaryModel: "gpt-4.1-mini"
      }
    };

    const classifier = new RuleFirstLlmClassifier(settings);
    const result = await classifier.classify({
      item: {
        id: "1",
        path: "C:/a/photo.jpg",
        name: "photo.jpg",
        ext: "jpg",
        size: 10,
        createdAt: "2026-02-12T00:00:00.000Z",
        modifiedAt: "2026-02-12T00:00:00.000Z",
        mime: "image/jpeg"
      },
      summary: {
        textSnippet: "",
        keywords: [],
        language: "zh-CN"
      }
    });

    expect(result?.purpose).toBe("Media");
    expect(result?.reasons).toContain("llm-fallback-rule:media");
  });
});
